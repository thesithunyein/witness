#!/usr/bin/env bun
/**
 * Builds the deployable Worker into app/worker-dist/index.js.
 *
 * Also bakes the deployment manifest (contracts/deployments/<chain>.json, written
 * by the forge deploy script) into worker/deployment.generated.ts, so the Worker
 * never reads the filesystem and no contract address is ever hand-copied.
 *
 * The same manifest the contracts were deployed with supplies rpId/origin, so the
 * site and the on-chain verifier can only agree or fail loudly, never silently
 * disagree.
 *
 *   WITNESS_CHAIN_ID=10143 bun run build-worker.mjs
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { resolve } from "node:path";

const appRoot = import.meta.dir;
const repoRoot = resolve(appRoot, "..");
const chainId = process.env.WITNESS_CHAIN_ID ?? "10143";
const manifestPath = resolve(repoRoot, "contracts", "deployments", `${chainId}.json`);

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
if (Number(manifest.chainId) !== Number(chainId)) {
  throw new Error(`manifest chainId ${manifest.chainId} != requested ${chainId}`);
}

const generated = `// AUTO-GENERATED by build-worker.mjs from contracts/deployments/${chainId}.json
// Do not edit by hand: redeploy or fix the manifest, then rebuild.
// rpId/origin here must match the values the contracts were deployed with.
//
// Two consumers, one source of truth:
//   - the Cloudflare Worker bundle (worker/index.ts)
//   - the Next.js server routes on Vercel (lib/server/deployment.ts), where
//     ../contracts is outside the serverless file-tracing root and cannot be
//     read at runtime
export const DEPLOYMENT = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync(resolve(appRoot, "worker", "deployment.generated.ts"), generated);
writeFileSync(resolve(appRoot, "lib", "server", "deployment.generated.ts"), generated);

const outDir = resolve(appRoot, "worker-dist");
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const result = await Bun.build({
  entrypoints: [resolve(appRoot, "worker", "index.ts")],
  outdir: outDir,
  target: "browser", // fails the build on any Node-only import: workerd has no Node builtins
  format: "esm",
  minify: true,
  sourcemap: false,
  naming: "index.js",
  define: { "process.env.NODE_ENV": '"production"' },
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}

for (const o of result.outputs) {
  const name = o.path.split(/[\\/]/).pop();
  console.log(`  ${name}  ${(o.size / 1024).toFixed(1)} kB`);
}
console.log(`worker built -> ${outDir} (chain ${chainId}, rpId ${manifest.rpId})`);
