// Generates a REAL WebAuthn/P-256 assertion vector for Witness.
//
// Why this script exists: WebAuthn's signed payload is
//     sha256( authenticatorData || sha256(clientDataJSON) )
// and the platform authenticator signs that 32-byte digest DIRECTLY.
// Node's crypto.sign("sha256", data, key) would hash it a second time, producing
// a signature the chain rejects. So we use @noble/curves with prehash:false,
// which signs the digest exactly like a real authenticator does.
//
// Emits:
//   contracts/test/vectors/AssertionVector.sol   -> Foundry fixture
//   contracts/test/vectors/AssertionVector.json  -> same data for CLI/tests
//
// Deterministic: fixed test key + RFC 6979 deterministic ECDSA, so the vector
// is stable across runs. The key is a throwaway with no on-chain value.

import { p256 } from "@noble/curves/nist.js";
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const RP_ID = "witness.sithunyein.com";
const ORIGIN = "https://witness.sithunyein.com";

const sha256 = (buf) => createHash("sha256").update(buf).digest();
const hex = (b) => "0x" + Buffer.from(b).toString("hex");
const b64url = (buf) => Buffer.from(buf).toString("base64url");

// Deterministic throwaway test identity.
const PRIV = sha256(Buffer.from("witness:test:key:1"));
const PUB = p256.getPublicKey(PRIV, false); // 0x04 || x(32) || y(32)
const qx = PUB.subarray(1, 33);
const qy = PUB.subarray(33, 65);

// The digest the human is approving. In the live protocol this is the canonical
// actionHash produced by AgentExecutor; fixed here for a readable fixture.
const CHALLENGE = sha256(Buffer.from("witness:demo:intent:1:transfer:1e18"));

// --- authenticatorData: rpIdHash(32) || flags(1) || signCount(4) -------------
const flags = Buffer.from([0x05]); // UP (0x01) | UV (0x04)
const signCount = Buffer.from([0, 0, 0, 1]);
const authenticatorData = Buffer.concat([sha256(Buffer.from(RP_ID)), flags, signCount]);

// --- clientDataJSON ---------------------------------------------------------
const challengeB64 = b64url(CHALLENGE);
const clientDataJSON = Buffer.from(
  JSON.stringify({ type: "webauthn.get", challenge: challengeB64, origin: ORIGIN }),
  "utf8"
);

// --- the exact digest a platform authenticator signs ------------------------
const messageHash = sha256(
  Buffer.concat([authenticatorData, sha256(clientDataJSON)])
);

// prehash: false -> sign the 32-byte digest directly (this is the whole point).
// noble 2.x returns the encoded signature bytes (64-byte compact r||s).
const compact = p256.sign(messageHash, PRIV, { prehash: false });
if (compact.length !== 64) {
  throw new Error(`expected 64-byte compact signature, got ${compact.length}`);
}
const r = compact.subarray(0, 32);
const s = compact.subarray(32, 64);

const precompileInput = Buffer.concat([messageHash, r, s, qx, qy]);

const data = {
  rpId: RP_ID,
  origin: ORIGIN,
  challenge: hex(CHALLENGE),
  challengeB64,
  authenticatorData: hex(authenticatorData),
  clientDataJSON: clientDataJSON.toString("utf8"),
  messageHash: hex(messageHash),
  r: hex(r),
  s: hex(s),
  qx: hex(qx),
  qy: hex(qy),
  signatureCompact: hex(compact),
  precompileInput: hex(precompileInput),
  testPrivateKey: hex(PRIV),
};

const solidity = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.20;

// AUTO-GENERATED by scripts/gen-assertion.mjs - do not edit by hand.
// A genuine P-256 / WebAuthn assertion: the signature below is a real ECDSA
// signature over sha256(authenticatorData || sha256(clientDataJSON)), produced
// by a platform-authenticator-equivalent path (raw-digest ECDSA, RFC 6979).
library AssertionVector {
    string internal constant RP_ID = "${data.rpId}";
    string internal constant ORIGIN = "${data.origin}";

    bytes32 internal constant CHALLENGE = ${data.challenge};
    string internal constant CHALLENGE_B64 = "${data.challengeB64}";

    bytes32 internal constant MESSAGE_HASH = ${data.messageHash};

    string internal constant CLIENT_DATA_JSON = '${data.clientDataJSON}';

    // rpIdHash || flags(UP|UV) || signCount
    bytes internal constant AUTHENTICATOR_DATA =
        hex"${data.authenticatorData.slice(2)}";

    uint256 internal constant R = ${BigInt(data.r)};
    uint256 internal constant S = ${BigInt(data.s)};
    uint256 internal constant QX = ${BigInt(data.qx)};
    uint256 internal constant QY = ${BigInt(data.qy)};

    // messageHash || r || s || qx || qy -> input for the 0x0100 precompile
    bytes internal constant PRECOMPILE_INPUT =
        hex"${data.precompileInput.slice(2)}";
}
`;

// Fixtures live inside the Foundry project so `forge test` can import them.
const VECTOR_DIR = resolve(ROOT, "contracts/test/vectors");
mkdirSync(VECTOR_DIR, { recursive: true });
writeFileSync(resolve(VECTOR_DIR, "AssertionVector.sol"), solidity);
writeFileSync(resolve(VECTOR_DIR, "AssertionVector.json"), JSON.stringify(data, null, 2) + "\n");

// Local sanity check with noble's own verifier before we ask the chain.
const localOk = p256.verify(compact, messageHash, PUB, { prehash: false });
const doubleHashed = p256.verify(compact, messageHash, PUB, { prehash: true });
if (doubleHashed) throw new Error("signature is over the digest, not a re-hash - bad fixture");
console.log(`local noble verify: ${localOk ? "PASS" : "FAIL"}`);
console.log(`rpId       : ${RP_ID}`);
console.log(`messageHash: ${data.messageHash}`);
console.log(`r          : ${data.r}`);
console.log(`s          : ${data.s}`);
console.log(`precompileInput (${precompileInput.length} bytes):`);
console.log(data.precompileInput);
if (!localOk) process.exit(1);
